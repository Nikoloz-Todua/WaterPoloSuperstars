        static Texture2D DeckTexture()
        {
            string path=Root+"/Textures/NeutralCeramic.png";
            if(!File.Exists(path))
            {
                const int size=128;var texture=new Texture2D(size,size,TextureFormat.RGBA32,false);var pixels=new Color32[size*size];var random=new System.Random(1984);
                for(int y=0;y<size;y++)for(int x=0;x<size;x++){bool grout=x<2||y<2;float grain=(float)random.NextDouble()*.035f;byte c=(byte)((grout?.71f:.91f+grain)*255);pixels[y*size+x]=new Color32(c,c,c,255);}
                texture.SetPixels32(pixels);texture.Apply();File.WriteAllBytes(path,texture.EncodeToPNG());Object.DestroyImmediate(texture);AssetDatabase.ImportAsset(path,ImportAssetOptions.ForceSynchronousImport);
                var importer=(TextureImporter)AssetImporter.GetAtPath(path);importer.mipmapEnabled=true;importer.isReadable=false;importer.wrapMode=TextureWrapMode.Repeat;importer.filterMode=FilterMode.Bilinear;importer.anisoLevel=2;importer.maxTextureSize=128;importer.textureCompression=TextureImporterCompression.CompressedHQ;importer.SaveAndReimport();
            }
            return AssetDatabase.LoadAssetAtPath<Texture2D>(path);
        }
        static void ThemeExistingSurfaces(Transform environment)
        {
            var deck=environment.Find("Non-slip Deck and Referee Safety Paths");
            foreach(var renderer in deck.GetComponentsInChildren<MeshRenderer>())
                if(renderer.name.Contains("tiled deck"))renderer.sharedMaterial=tile;
                else if(renderer.name.Contains("fascia"))renderer.sharedMaterial=pearl;
            var hall=environment.Find("Aquatic Centre Architecture");
            foreach(var renderer in hall.GetComponentsInChildren<MeshRenderer>())
            {
                if(renderer.name.Contains("concourse"))renderer.sharedMaterial=tile;
                if(renderer.name.Contains("arena wall"))renderer.sharedMaterial=pearl;
                if(renderer.name.Contains("competition fascia")||renderer.name.Contains("turquoise fascia"))renderer.sharedMaterial=cobalt;
            }
        }
